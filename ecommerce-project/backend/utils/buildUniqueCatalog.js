async function run() {
  console.log('Verifying uniqueness of 180 products catalog...');

  const imageMap = {};
  const nameMap = {};
  const categoryCounts = {};

  uniqueCatalog.forEach((p, idx) => {
    imageMap[p.image] = (imageMap[p.image] || 0) + 1;
    nameMap[p.name] = (nameMap[p.name] || 0) + 1;
    categoryCounts[p.category] = (categoryCounts[p.category] || 0) + 1;
    p.images = [p.image];
  });

  const dupImages = Object.entries(imageMap).filter(([k, v]) => v > 1);
  const dupNames = Object.entries(nameMap).filter(([k, v]) => v > 1);

  if (dupImages.length > 0) {
    console.error('❌ Duplicate Images detected:', dupImages);
    process.exit(1);
  }
  if (dupNames.length > 0) {
    console.error('❌ Duplicate Names detected:', dupNames);
    process.exit(1);
  }

  console.log('✅ ZERO duplicate images found! Total unique images:', Object.keys(imageMap).length);
  console.log('✅ ZERO duplicate product names found! Total unique products:', Object.keys(nameMap).length);
  console.log('Category Counts:', categoryCounts);

  // Connect to MongoDB
  console.log('Connecting to MongoDB Atlas...');
  await mongoose.connect(process.env.MONGODB_URI);
  console.log('✅ Connected to MongoDB Atlas');

  await Product.deleteMany({});
  console.log('🗑️  Emptied products collection');

  const inserted = await Product.insertMany(uniqueCatalog);
  console.log(`🎉 Inserted ${inserted.length} completely unique products into MongoDB!`);

  // Synchronize frontend/src/data/products.js
  const frontendPath = path.resolve(__dirname, '../../frontend/src/data/products.js');
  const frontendData = inserted.map((doc) => ({
    _id: doc._id.toString(),
    id: doc._id.toString(),
    name: doc.name,
    price: doc.price,
    originalPrice: doc.originalPrice,
    rating: doc.rating,
    sold: doc.sold,
    stock: doc.stock,
    discount: doc.discount,
    image: doc.image,
    images: doc.images,
    category: doc.category,
    subcategory: doc.subcategory,
    brand: doc.brand,
    keywords: doc.keywords,
    description: doc.description,
    featured: doc.featured,
    isNew: doc.isNew,
  }));

  const fileContent = `// Auto-generated 100% unique product catalog (${frontendData.length} unique items)
export const products = ${JSON.stringify(frontendData, null, 2)};

export default products;
`;

  fs.writeFileSync(frontendPath, fileContent, 'utf8');
  console.log(`✅ Saved ${frontendData.length} unique items to ${frontendPath}!`);

  await mongoose.disconnect();
  console.log('✅ Finished successfully.');
  process.exit(0);
}

