async function addMore() {
  try {
    console.log('Connecting to MongoDB Atlas...');
    await mongoose.connect(process.env.MONGODB_URI);
    console.log('✅ Connected to MongoDB Atlas');

    const catCounts = {};
    allProducts.forEach((p) => {
      catCounts[p.category] = (catCounts[p.category] || 0) + 1;
      p.images = [p.image];
    });

    console.log('Total items per category:', catCounts);
    console.log(`Total items to insert across all categories: ${allProducts.length}`);

    await Product.deleteMany({});
    console.log('🗑️  Cleared old products collection');

    const inserted = await Product.insertMany(allProducts);
    console.log(`🎉 Successfully saved ${inserted.length} products to MongoDB Atlas!`);

    // Verify
    const finalCounts = {};
    for (const doc of inserted) {
      finalCounts[doc.category] = (finalCounts[doc.category] || 0) + 1;
    }
    console.log('Verified product counts per category in DB:', finalCounts);

    // Sync frontend fallback file
    const frontendProductsPath = path.resolve(__dirname, '../../frontend/src/data/products.js');
    const frontendData = inserted.map((doc) => ({
      _id: doc._id.toString(),
      id: doc._id.toString(),
      name: doc.name,
      price: doc.price,
      originalPrice: doc.originalPrice,
      rating: doc.rating,
      sold: doc.sold,
      stock: doc.stock,
      discount: doc.discount,
      image: doc.image,
      images: doc.images,
      category: doc.category,
      subcategory: doc.subcategory,
      brand: doc.brand,
      keywords: doc.keywords,
      description: doc.description,
      featured: doc.featured,
      isNew: doc.isNew,
    }));

    const fileContent = `// Auto-generated synchronized product catalog (${frontendData.length} items)
export const products = ${JSON.stringify(frontendData, null, 2)};

export default products;
`;

    fs.writeFileSync(frontendProductsPath, fileContent, 'utf8');
    console.log(`✅ Synchronized frontend data at ${frontendProductsPath} with ${frontendData.length} products!`);

    await mongoose.disconnect();
    console.log('✅ Disconnected from database.');
    process.exit(0);
  } catch (err) {
    console.error('❌ Error during expansion:', err);
    process.exit(1);
  }
}

addMore();
